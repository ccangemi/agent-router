#!/usr/bin/env bash
# Moves the operator to the versions in versions.env. Run it after you change
# CHART_VERSION or OPERATOR_VERSION, then run `make bundle` and commit the
# result.
#
#   hack/update-upstream.sh      (or: make update-upstream)
#
# It needs network access. It writes:
#   helm-charts/agent-router/charts/<chart>/   the upstream chart, unchanged
#   helm-charts/agent-router/Chart.yaml        versions
#   helm-charts/agent-router/values.yaml       the images, pinned by digest
#   config/manifests/related-images.yaml       the same images, for the bundle
#   config/crd/upstream/                       the Agent Router CRDs, one per file
#   config/crd/kustomization.yaml              the list of CRDs
#   config/rbac/role.yaml                      the operator permissions (hack/generate-rbac.sh)

# shellcheck source=hack/lib.sh
source "$(dirname "$0")/lib.sh"
require_tools HELM YQ

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

pull() {
  log "pulling $1 $2"
  mkdir -p "$work/$1"
  "$HELM" pull "$CHART_OCI/$1" --version "$2" --untar --untardir "$work/$1" >/dev/null 2>&1 \
    || fail "cannot pull $CHART_OCI/$1 $2"
}
pull "$CHART_NAME" "$CHART_VERSION"
pull "$CRDS_CHART_NAME" "$CHART_VERSION"

# --- The chart -----------------------------------------------------------------
log "copying $CHART_NAME $CHART_VERSION to ${UPSTREAM_CHART_DIR#"$ROOT_DIR"/} (unchanged)"
rm -rf "$UPSTREAM_CHART_DIR"
mkdir -p "$(dirname "$UPSTREAM_CHART_DIR")"
cp -a "$work/$CHART_NAME/$CHART_NAME" "$UPSTREAM_CHART_DIR"
export OPERATOR_VERSION CHART_VERSION CHART_NAME
"$YQ" -i '.version = strenv(OPERATOR_VERSION) | .appVersion = strenv(CHART_VERSION)
  | (.dependencies[] | select(.name == strenv(CHART_NAME)) | .version) = strenv(CHART_VERSION)' "$CHART_DIR/Chart.yaml"

# --- The CRDs ------------------------------------------------------------------
log "rendering the Agent Router CRDs"
"$HELM" template crds "$work/$CRDS_CHART_NAME/$CRDS_CHART_NAME" >"$work/crds.yaml"
rm -rf "$ROOT_DIR/config/crd/upstream"
mkdir -p "$ROOT_DIR/config/crd/upstream"
# One file per CRD, named <group>_<plural>.yaml like operator-sdk does. Helm
# labels are removed: OLM owns these CRDs, not Helm.
(cd "$ROOT_DIR/config/crd/upstream" && "$YQ" -s '.spec.group + "_" + .spec.names.plural + ".yaml"' \
  'select(.kind == "CustomResourceDefinition")
   | del(.metadata.labels."helm.sh/chart", .metadata.labels."app.kubernetes.io/managed-by",
         .metadata.labels."app.kubernetes.io/instance", .metadata.annotations."helm.sh/resource-policy")
   | del(.metadata.labels | select(length == 0))
   | del(.metadata.annotations | select(length == 0))' \
  "$work/crds.yaml")
for f in "$ROOT_DIR"/config/crd/upstream/*.yaml; do
  # One document per file, without separators, comments or empty documents.
  "$YQ" -N 'select(.kind == "CustomResourceDefinition") | ... comments = ""' "$f" >"$work/crd.yaml"
  mv "$work/crd.yaml" "$f"
  group=$("$YQ" '.spec.group' "$f")
  [[ $group =~ $ALLOWED_CRD_GROUPS ]] || fail "$(basename "$f"): CRD group $group is not allowed"
done
{
  echo "# Generated by hack/update-upstream.sh. Do not edit."
  echo "# The CRD of the custom resource, then the Agent Router CRDs."
  echo "resources:"
  for f in "$ROOT_DIR"/config/crd/bases/*.yaml "$ROOT_DIR"/config/crd/upstream/*.yaml; do
    echo "  - ${f#"$ROOT_DIR"/config/crd/}"
  done
} >"$ROOT_DIR/config/crd/kustomization.yaml"

# --- Images --------------------------------------------------------------------
# The operator chart passes the images to the upstream chart by digest: the
# tag becomes "<appVersion>@<digest>". The bundle lists them in relatedImages,
# so that mirroring tools copy them.
log "resolving image digests"
values=$UPSTREAM_CHART_DIR/values.yaml
app_version=$("$YQ" '.appVersion' "$UPSTREAM_CHART_DIR/Chart.yaml")
CONTROLLER_REPOSITORY=$("$YQ" '.controller.image.repository' "$values")
EXTPROC_REPOSITORY=$("$YQ" '.extProc.image.repository' "$values")
CONTROLLER_TAG=$app_version@$(resolve_digest "$CONTROLLER_REPOSITORY:$app_version")
EXTPROC_TAG=$app_version@$(resolve_digest "$EXTPROC_REPOSITORY:$app_version")
export CONTROLLER_REPOSITORY EXTPROC_REPOSITORY CONTROLLER_TAG EXTPROC_TAG

"$YQ" -i '."ai-gateway-helm".controller.image.repository = strenv(CONTROLLER_REPOSITORY)
  | ."ai-gateway-helm".controller.image.tag = strenv(CONTROLLER_TAG)
  | ."ai-gateway-helm".extProc.image.repository = strenv(EXTPROC_REPOSITORY)
  | ."ai-gateway-helm".extProc.image.tag = strenv(EXTPROC_TAG)' "$CHART_DIR/values.yaml"
cat >"$ROOT_DIR/config/manifests/related-images.yaml" <<YAML
# Generated by hack/update-upstream.sh. Do not edit.
# The operand images. hack/generate-bundle.sh adds them, and the operator
# image, to spec.relatedImages of the ClusterServiceVersion.
- name: ai-gateway-controller
  image: $CONTROLLER_REPOSITORY:$CONTROLLER_TAG
- name: ai-gateway-extproc
  image: $EXTPROC_REPOSITORY:$EXTPROC_TAG
YAML

# --- Permissions ---------------------------------------------------------------
"$ROOT_DIR/hack/generate-rbac.sh"

log "done. Review the changes, then run 'make bundle'."
